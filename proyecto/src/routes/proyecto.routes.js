const router = require('express').Router();
const { verificarToken, soloRoles } = require('../middleware/auth.middleware');
const wrap = require('../middleware/async');
const c = require('../controllers/proyecto.controller');
const capacidades337=require('../controllers/capacidades-proyecto-337.controller');
const finanzas348=require('../controllers/recursos-financieros-42001-348.controller');
const instrumento347=require('../controllers/instrumento-42001-registro-347.controller');
const avisosExperimentales = require('../controllers/notificaciones.controller');
const retencion = require('../controllers/conservacion.controller');
const adicionales = require('../controllers/acuerdos-adicionales.controller');
const cierre = require('../controllers/cierre.controller');
const planes = require('../controllers/planes.controller');
const q75=require('../controllers/regularizacion-plan.controller');
const multer=require('multer');
const crypto=require('node:crypto');
const path=require('node:path');
const fs=require('node:fs');
const {uploadDir}=require('../middleware/upload.middleware');
const q75Dir=path.join(uploadDir,'planes-regularizacion');
fs.mkdirSync(q75Dir,{recursive:true,mode:0o700});
const uploadQ75=multer({storage:multer.diskStorage({destination:(_r,_f,cb)=>cb(null,q75Dir),filename:(_r,_f,cb)=>cb(null,`${crypto.randomUUID()}.pdf`)}),
 limits:{fileSize:10*1024*1024,files:1,fields:12,parts:13,fieldNestingDepth:2,fieldNameSize:100,fieldSize:64*1024},
 fileFilter:(_r,f,cb)=>cb(null,f.mimetype==='application/pdf'&&path.extname(f.originalname).toLowerCase()==='.pdf')});
const {exigirPlanBrecha}=require('../middleware/plan-aceptado.middleware');
const anticipado = require('../controllers/terminacion-anticipada.controller');
router.use(verificarToken);
router.get('/', wrap(c.listar));
// BE-02 EXPERIMENTAL: listado mínimo; detalle explícito; confirmación automática.
router.get('/notificaciones/mias', wrap(avisosExperimentales.listar));
router.get('/notificaciones/:notificacionId', wrap(avisosExperimentales.abrirDetalle));
router.post('/notificaciones/:notificacionId/aperturas', wrap(avisosExperimentales.confirmarApertura));
router.patch('/notificaciones/:notificacionId/leida', avisosExperimentales.lecturaManualRetirada);
router.post('/', soloRoles('ADMIN'), wrap(c.crear));
router.get('/:id', wrap(c.obtener));
// F337: consulta de capacidades normativas sin heredar instrumento 27001 en 42001.
router.get('/:proyectoId/capacidades', wrap(capacidades337.consultar));
router.get('/:proyectoId/42001/recursos-financieros',wrap(finanzas348.consultar));
// F347: almacenamiento de borradores no aprobatorios (sin instrumento ejecutable).
router.post('/:proyectoId/instrumentos/42001/borradores',wrap(instrumento347.registrar));
router.get('/:proyectoId/planes', wrap(planes.listar));
router.get('/:proyectoId/planes/regularizacion/elegibles',wrap(q75.listarElegibles));
router.post('/:proyectoId/planes/regularizacion',wrap(q75.preparar),uploadQ75.single('evidencia'),wrap(q75.registrar));
router.get('/:proyectoId/planes/:versionId/evidencia-historica',wrap(q75.descargar));
router.post('/:proyectoId/planes', wrap(planes.proponer));
router.post('/:proyectoId/planes/:versionId/aceptacion-externa', wrap(planes.aceptar));
router.post('/:proyectoId/planes/:versionId/no-aceptacion', wrap(planes.noAceptar));
router.post('/:proyectoId/planes/:versionId/retirar', wrap(planes.retirar));
router.get('/:proyectoId/acuerdos-adicionales', wrap(adicionales.listar));
router.post('/:proyectoId/acuerdos-adicionales', wrap(adicionales.proponer));
router.post('/:proyectoId/acuerdos-adicionales/:acuerdoId/confirmar', soloRoles('ADMIN'), wrap(adicionales.confirmar));
router.post('/:proyectoId/acuerdos-adicionales/:acuerdoId/aceptacion', wrap(adicionales.registrarAceptacion));
router.post('/:proyectoId/acuerdos-adicionales/:acuerdoId/cambio', soloRoles('ADMIN'), wrap(adicionales.registrarCambio));
router.get('/:proyectoId/conservacion', wrap(retencion.historial));
router.get('/:proyectoId/cierre/prevalidacion', wrap(cierre.prevalidacion));
router.get('/:proyectoId/cierre/anticipado', wrap(anticipado.consultar));
router.post('/:proyectoId/cierre/anticipado', soloRoles('ADMIN'), wrap(anticipado.terminar));
router.post('/:proyectoId/conservacion', soloRoles('ADMIN'), wrap(retencion.registrar));
router.get('/:proyectoId/consultores-disponibles', soloRoles('ADMIN','EVALUADOR'), wrap(c.consultoresDisponibles));
router.post('/:proyectoId/consultores', soloRoles('ADMIN','EVALUADOR'), wrap(c.asignar));
router.delete('/:proyectoId/consultores/:usuarioId', soloRoles('ADMIN','EVALUADOR'), wrap(c.retirar));
router.get('/:proyectoId/diagnosticos', wrap(c.diagnosticos));
router.post('/:proyectoId/diagnosticos', wrap(c.iniciarDiagnostico));
router.get('/:proyectoId/diagnosticos/:diagnosticoId', wrap(c.detalleDiagnostico));
router.post('/:proyectoId/diagnosticos/:diagnosticoId/comentarios', wrap(c.revisarDiagnostico));
router.get('/:proyectoId/brechas', wrap(c.listarBrechas));
router.post('/:proyectoId/brechas', wrap(c.registrarBrecha));
router.post('/:proyectoId/brechas/:brechaId/proponer-cierre',wrap(exigirPlanBrecha), wrap(c.proponerCierreBrecha));
router.post('/:proyectoId/brechas/:brechaId/reabrir', wrap(c.reabrirBrecha));
router.get('/:proyectoId/brechas/:brechaId/historial', wrap(c.historialBrecha));
router.get('/:proyectoId/actividades', wrap(c.listarActividades));
router.post('/:proyectoId/actividades', wrap(c.registrarActividad));
router.patch('/:proyectoId/actividades/:actividadId', wrap(c.actualizarActividad));
router.post('/:proyectoId/actividades/:actividadId/anular', wrap(c.anularActividadAntecedente));
router.post('/:proyectoId/actividades/:actividadId/retirar-rama', wrap(c.retirarRamaAlcance));
router.post('/:proyectoId/actividades/:actividadId/excluir-brecha', wrap(c.excluirVinculoActividadBrecha));
router.post('/:proyectoId/actividades/:actividadId/constancias-alcance', wrap(c.registrarConstanciaAlcanceCompletada));
router.get('/:proyectoId/actividades/:actividadId/constancias-alcance', wrap(c.listarConstanciasAlcanceCompletada));
router.patch('/:proyectoId/actividades/:actividadId/fecha-objetivo', wrap(c.cambiarFechaObjetivo));
router.patch('/:proyectoId/actividades/:actividadId/responsable', wrap(c.reasignarActividad));
router.patch('/:proyectoId/actividades/:actividadId/revisor', wrap(c.designarRevisorActividad));
module.exports = router;
